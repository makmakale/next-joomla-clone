import * as p from 'drizzle-orm/pg-core';

export const ucmContentTable = p.pgTable(
    'ucm_content',
    {
        coreContentId: p.serial('core_content_id').notNull().primaryKey(),
        coreTypeAlias: p.varchar('core_type_alias', { length: 255 }).default('').notNull(),
        coreTitle: p.varchar('core_title', { length: 255 }).default('').notNull(),
        coreAlias: p.varchar('core_alias', { length: 255 }).default('').notNull(),
        coreBody: p.text('core_body'),
        coreState: p.smallint('core_state').default(0).notNull(),
        coreCheckedOutTime: p.timestamp('core_checked_out_time', { mode: 'date' }),
        coreCheckedOutUserId: p.integer('core_checked_out_user_id'),
        coreAccess: p.bigint('core_access', { mode: 'number' }).default(0).notNull(),
        coreParams: p.jsonb('core_params'),
        coreFeatured: p.boolean('core_featured').default(false).notNull(),
        coreMetadata: p.jsonb('core_metadata'),
        coreCreatedUserId: p.bigint('core_created_user_id', { mode: 'number' }).default(0).notNull(),
        coreCreatedByAlias: p.varchar('core_created_by_alias', { length: 255 }).default('').notNull(),
        coreCreatedTime: p.timestamp('core_created_time', { mode: 'date' }).notNull(),
        coreModifiedUserId: p.bigint('core_modified_user_id', { mode: 'number' }).default(0).notNull(),
        coreModifiedTime: p.timestamp('core_modified_time', { mode: 'date' }).notNull(),
        coreLanguage: p.varchar('core_language', { length: 7 }).default('').notNull(),
        corePublishUp: p.timestamp('core_publish_up', { mode: 'date' }),
        corePublishDown: p.timestamp('core_publish_down', { mode: 'date' }),
        coreContentItemId: p.bigint('core_content_item_id', { mode: 'number' }).default(0).notNull(),
        assetId: p.bigint('asset_id', { mode: 'number' }).default(0).notNull(),
        coreImages: p.jsonb('core_images'),
        coreUrls: p.jsonb('core_urls'),
        coreHits: p.bigint('core_hits', { mode: 'number' }).default(0).notNull(),
        coreVersion: p.bigint('core_version', { mode: 'number' }).default(1).notNull(),
        coreOrdering: p.bigint('core_ordering', { mode: 'number' }).default(0).notNull(),
        coreMetakey: p.text('core_metakey'),
        coreMetadesc: p.text('core_metadesc'),
        coreCatid: p.bigint('core_catid', { mode: 'number' }).default(0).notNull(),
        coreTypeId: p.bigint('core_type_id', { mode: 'number' }).default(0).notNull(),
    },
    table => [
        p.index('ucm_content_tag_idx').on(table.coreState, table.coreAccess),
        p.index('ucm_content_idx_access').on(table.coreAccess),
        p.index('ucm_content_idx_alias').on(table.coreAlias),
        p.index('ucm_content_idx_language').on(table.coreLanguage),
        p.index('ucm_content_idx_title').on(table.coreTitle),
        p.index('ucm_content_idx_modified_time').on(table.coreModifiedTime),
        p.index('ucm_content_idx_created_time').on(table.coreCreatedTime),
        p.index('ucm_content_idx_content_type').on(table.coreTypeAlias),
        p.index('ucm_content_idx_core_modified_user_id').on(table.coreModifiedUserId),
        p.index('ucm_content_idx_core_checked_out_user_id').on(table.coreCheckedOutUserId),
        p.index('ucm_content_idx_core_created_user_id').on(table.coreCreatedUserId),
        p.index('ucm_content_idx_core_type_id').on(table.coreTypeId),
    ],
);

export type UcmContent = typeof ucmContentTable.$inferSelect;
export type NewUcmContent = typeof ucmContentTable.$inferInsert;
