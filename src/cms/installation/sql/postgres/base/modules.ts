function transform(
    id: number,
    assetId: number,
    title: string,
    note: string,
    content: string,
    ordering: number,
    position: string,
    publishUp: Date | null,
    publishDown: Date | null,
    published: number,
    module: string,
    access: number,
    showTitle: number,
    params: string,
    clientId: number,
    language: string,
): NewModule {
    return {
        id,
        assetId,
        title,
        note,
        content,
        ordering,
        position,
        publishUp,
        publishDown,
        published,
        module,
        access,
        showTitle: Boolean(showTitle),
        params,
        clientId,
        language,
    };
}
