import * as p from 'drizzle-orm/pg-core';

export const contactDetailsTable = p.pgTable(
    'contact_details',
    {
        id: p.serial('id').notNull().primaryKey(),
        name: p.varchar('name', { length: 255 }).notNull(),
        alias: p.varchar('alias', { length: 255 }).notNull(),
        conPosition: p.varchar('con_position', { length: 255 }),
        address: p.text('address'),
        suburb: p.varchar('suburb', { length: 100 }),
        state: p.varchar('state', { length: 100 }),
        country: p.varchar('country', { length: 100 }),
        postcode: p.varchar('postcode', { length: 100 }),
        telephone: p.varchar('telephone', { length: 255 }),
        fax: p.varchar('fax', { length: 255 }),
        misc: p.text('misc'),
        image: p.varchar('image', { length: 255 }),
        emailTo: p.varchar('email_to', { length: 255 }),
        defaultCon: p.boolean('default_con').default(false).notNull(),
        published: p.smallint('published').default(0).notNull(),
        checkedOut: p.integer('checked_out'),
        checkedOutTime: p.timestamp('checked_out_time', { mode: 'date' }),
        ordering: p.bigint('ordering', { mode: 'number' }).default(0).notNull(),
        params: p.jsonb('params').notNull().default({}),
        userId: p.bigint('user_id', { mode: 'number' }).default(0).notNull(),
        catid: p.bigint('catid', { mode: 'number' }).default(0).notNull(),
        access: p.bigint('access', { mode: 'number' }).default(0).notNull(),
        mobile: p.varchar('mobile', { length: 255 }).default('').notNull(),
        webpage: p.varchar('webpage', { length: 255 }).default('').notNull(),
        sortname1: p.varchar('sortname1', { length: 255 }).default('').notNull(),
        sortname2: p.varchar('sortname2', { length: 255 }).default('').notNull(),
        sortname3: p.varchar('sortname3', { length: 255 }).default('').notNull(),
        language: p.varchar('language', { length: 7 }).notNull(),
        created: p.timestamp('created', { mode: 'date' }).notNull(),
        createdBy: p.integer('created_by').default(0).notNull(),
        createdByAlias: p.varchar('created_by_alias', { length: 255 }).default('').notNull(),
        modified: p.timestamp('modified', { mode: 'date' }).notNull(),
        modifiedBy: p.integer('modified_by').default(0).notNull(),
        metakey: p.text('metakey'),
        metadesc: p.text('metadesc').notNull(),
        metadata: p.jsonb('metadata').notNull().default({}),
        featured: p.boolean('featured').default(false).notNull(),
        publishUp: p.timestamp('publish_up', { mode: 'date' }),
        publishDown: p.timestamp('publish_down', { mode: 'date' }),
        version: p.bigint('version', { mode: 'number' }).default(1).notNull(),
        hits: p.bigint('hits', { mode: 'number' }).default(0).notNull(),
    },
    table => [
        p.index('contact_details_idx_access').on(table.access),
        p.index('contact_details_idx_checkout').on(table.checkedOut),
        p.index('contact_details_idx_state').on(table.published),
        p.index('contact_details_idx_catid').on(table.catid),
        p.index('contact_details_idx_createdby').on(table.createdBy),
        p.index('contact_details_idx_featured_catid').on(table.featured, table.catid),
        p.index('contact_details_idx_language').on(table.language),
    ],
);

export type ContactDetail = typeof contactDetailsTable.$inferSelect;
export type NewContactDetail = typeof contactDetailsTable.$inferInsert;
